/**
 * Canonical meteorological data contracts used by the ClimaBR ingestion layer.
 *
 * These types are intentionally independent from the current dashboard model
 * in types/station.ts. Source adapters should normalize provider records into
 * these contracts before data is exposed to the UI.
 */

export type ObservationVariable =
  | "air_temperature"
  | "relative_humidity"
  | "air_pressure"
  | "precipitation"
  | "wind_speed"
  | "wind_direction"
  | "dew_point"
  | "solar_radiation";

export type ObservationUnit =
  | "Cel"
  | "%"
  | "hPa"
  | "mm"
  | "m/s"
  | "degree"
  | "W/m2";

export type AggregationType =
  | "instant"
  | "mean"
  | "sum"
  | "maximum"
  | "minimum"
  | "unknown";

export type QualityStatus =
  | "unchecked"
  | "valid"
  | "suspect"
  | "invalid"
  | "missing";

export interface DataSource {
  /** Stable internal identifier, for example: "INMET". */
  id: string;
  provider: string;
  product: string;
  documentationUrl?: string;
  termsOfUseUrl?: string;
}

export interface SourceReference {
  sourceId: string;
  /** Identifier assigned to the station by the original provider. */
  sourceStationId: string;
  /** Original record, file, or product identifier when available. */
  sourceRecordId?: string;
  /** URL or object-storage key identifying the original resource. */
  resourceReference?: string;
}

export interface MeteorologicalStation {
  id: string;
  source: SourceReference;
  name: string;
  municipality?: string;
  state?: string;
  latitude: number;
  longitude: number;
  elevationMeters?: number;
  stationType?: string;
  validFrom?: string;
  validUntil?: string;
}

export interface ObservationAggregation {
  type: AggregationType;
  /** Duration represented by the value. Null means instantaneous/unspecified. */
  intervalMinutes: number | null;
}

export interface ObservationQuality {
  status: QualityStatus;
  /** Machine-readable identifiers for the checks or issues detected. */
  flags: string[];
  /** Version of the quality-control rules applied, when available. */
  rulesetVersion?: string;
}

export interface MeteorologicalObservation {
  /** Stable identifier generated by the ingestion layer. */
  id: string;
  stationId: string;
  source: SourceReference;
  variable: ObservationVariable;
  value: number | null;
  unit: ObservationUnit;
  /** Time the measurement refers to, serialized as ISO 8601 UTC. */
  observedAt: string;
  /** Time ClimaBR acquired this record, serialized as ISO 8601 UTC. */
  receivedAt: string;
  aggregation: ObservationAggregation;
  quality: ObservationQuality;
}

export type IngestionStatus = "running" | "succeeded" | "partial" | "failed";

export interface IngestionRun {
  id: string;
  sourceId: string;
  startedAt: string;
  completedAt?: string;
  status: IngestionStatus;
  recordsReceived: number;
  recordsNormalized: number;
  recordsRejected: number;
  errorMessage?: string;
}
